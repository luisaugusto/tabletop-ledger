import Foundation
let me = Player(name: "Me", isMe: true)
let friend = Player(name: "Alex")
let both = GameSession(game: "Tie", entries: [Entry(playerID: me.id, isWinner: true), Entry(playerID: friend.id, isWinner: true)])
let loss = GameSession(game: "Loss", entries: [Entry(playerID: me.id), Entry(playerID: friend.id, isWinner: true)])
let undecided = GameSession(game: "No result", entries: [Entry(playerID: me.id), Entry(playerID: friend.id)])
let stats = PlayerStats.calculate(me.id, sessions: [both, loss, undecided])
assert(stats.played == 3 && stats.wins == 1 && stats.decided == 2 && stats.rate == "50%")
assert(PlayerStats.calculate(friend.id, sessions: [both, loss]).rate == "100%")
assert(PlayerStats.calculate(me.id, sessions: [undecided]).rate == "—")
var withPhoto = both
withPhoto.photo = Data([0xFF, 0xD8, 0xFF, 0xE0])
let journal = JournalData(players: [me, friend], sessions: [withPhoto, loss, undecided])
let data = try JSONEncoder().encode(journal)
let roundtrip = try JSONDecoder().decode(JournalData.self, from: data)
assert(roundtrip.sessions == journal.sessions && roundtrip.players == journal.players)
assert(roundtrip.sessions[0].photo == withPhoto.photo)
let url = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent(UUID().uuidString)
try data.write(to: url, options: .atomic)
let disk = try JSONDecoder().decode(JournalData.self, from: Data(contentsOf: url))
assert(disk.sessions[0].photo == withPhoto.photo)
try FileManager.default.removeItem(at: url)
print("PASS: photo byte persistence, atomic disk read/write, multiple winners, loss, no-result exclusion, empty denominator, JSON round-trip")
